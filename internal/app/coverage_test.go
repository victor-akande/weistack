package app

import (
	"flag"
	"fmt"
	"os"
	"slices"
	"strings"
	"testing"

	"github.com/victor-akande/weistack/internal/core/actions"
)

var update = flag.Bool("update", false, "rewrite docs/coverage.md")

// coveragePath is the generated coverage page, from this package.
const coveragePath = "../../docs/coverage.md"

// TestCoverageDoc checks that docs/coverage.md lists exactly the routes
// WeiStack serves and the IAM action each checks. After changing routes
// or actions, regenerate it with:
//
//	go test ./internal/app -run TestCoverageDoc -update
func TestCoverageDoc(t *testing.T) {
	got := coverageDoc(t)
	if *update {
		if err := os.WriteFile(coveragePath, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(coveragePath)
	if err != nil {
		t.Fatal(err)
	}
	if string(want) != got {
		t.Error("docs/coverage.md is out of date; run: go test ./internal/app -run TestCoverageDoc -update")
	}
}

type serviceCoverage struct {
	name, version string
	rows          []string
}

func coverageDoc(t *testing.T) string {
	t.Helper()
	var services []*serviceCoverage
	// KMS checks the action once the body names a key, before it looks
	// the key up: any key ID shows which action an operation needs.
	probeRoutes(t, `{"key_id": "0d0466b0-ac9e-4ee5-8a5c-08b5ee2e5ab3"}`, func(p probe) {
		if len(services) == 0 || services[len(services)-1].name != p.service {
			services = append(services, &serviceCoverage{name: p.service, version: p.version})
		}
		s := services[len(services)-1]
		if p.service == "obs" {
			return // one catch-all route, described by its actions below
		}
		s.rows = append(s.rows, fmt.Sprintf("| `%s` | `%s` | %s |", p.method, p.route, permission(p)))
	})

	var b strings.Builder
	b.WriteString(`# Coverage

<!-- Generated by TestCoverageDoc (internal/app/coverage_test.go); do not
edit. Regenerate with: go test ./internal/app -run TestCoverageDoc -update -->

Every operation WeiStack serves, by service, with the IAM action that
authorizes it under ` + "`-iam=enforce`" + ` (see [Checking credentials](enforce.md)).
A request for anything else answers ` + "`501 WeiStack.0501`" + `. The pages under
[services](services/) describe each operation's behaviour and gaps.

| Service | API versions | Operations |
| --- | --- | --- |
`)
	for _, s := range services {
		n := len(s.rows)
		if s.name == "obs" {
			n = len(serviceActions("obs"))
		}
		fmt.Fprintf(&b, "| [%s](#%s) | %s | %d |\n", strings.ToUpper(s.name), s.name, s.version, n)
	}
	for _, s := range services {
		fmt.Fprintf(&b, "\n## %s\n\n", strings.ToUpper(s.name))
		fmt.Fprintf(&b, "Endpoint: `%s.{region}.myhuaweicloud.com`.", s.name)
		if _, err := os.Stat("../../docs/services/" + s.name + ".md"); err == nil {
			fmt.Fprintf(&b, " Details: [%s](services/%s.md).", strings.ToUpper(s.name), s.name)
		}
		b.WriteString("\n\n")
		if s.name == "obs" {
			b.WriteString("OBS serves every request through one route and picks the operation from the\n" +
				"method, the path and the query. The operations it serves, by IAM action:\n\n")
			for _, a := range serviceActions("obs") {
				fmt.Fprintf(&b, "- `%s`\n", a)
			}
			continue
		}
		b.WriteString("| Method | Path | IAM action |\n| --- | --- | --- |\n")
		for _, r := range s.rows {
			b.WriteString(r + "\n")
		}
	}
	return b.String()
}

// permission describes what authorizes a route: the actions it checked,
// or why it checked none.
func permission(p probe) string {
	if checked := p.gate.Checked(); len(checked) > 0 {
		return "`" + strings.Join(slices.Compact(checked), "`, `") + "`"
	}
	name := p.service + " " + p.method + " " + p.route
	switch why := openRoutes[name]; {
	case strings.HasPrefix(why, "documented:"):
		return "None needed"
	case strings.HasPrefix(why, "checked once the body names"):
		return "Depends on the body (" + strings.TrimPrefix(why, "checked once the body names ") + ")"
	case why != "":
		return "None needed (" + why + ")"
	}
	return "None"
}

// serviceActions lists a service's actions in the catalogue, sorted.
func serviceActions(service string) []string {
	var out []string
	for _, a := range actions.All() {
		if strings.HasPrefix(a.Name, service+":") {
			out = append(out, a.Name)
		}
	}
	slices.Sort(out)
	return out
}
